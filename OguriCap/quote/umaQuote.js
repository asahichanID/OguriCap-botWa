// =========================================================================
// HANDLER ROTASI NON-ACAK (FAIR SHUFFLE CYCLE / SHUFFLE BAG ALGORITHM)
// Mengambil quote secara variatif tanpa perulangan acak yang duplikat
// =========================================================================

let shufflePool = [];
let lastIndex = -1;

/**
 * Mengacak array dengan algoritma Fisher-Yates
 */
function shuffleArray(array) {
	const result = [...array];
	for (let i = result.length - 1; i > 0; i--) {
		const j = Math.floor(Math.random() * (i + 1));
		[result[i], result[j]] = [result[j], result[i]];
	}
	return result;
}

/**
 * Mengisi ulang pool antrean indeks dengan aman,
 * menjamin elemen pertama di putaran baru tidak sama dengan elemen terakhir di putaran sebelumnya.
 */
function refillPool() {
	const indices = Array.from({ length: umaQuotes.length }, (_, i) => i);
	let shuffled = shuffleArray(indices);

	// Jika elemen pertama sama dengan elemen terakhir di cycle sebelumnya, geser posisi
	if (shuffled.length > 1 && shuffled[0] === lastIndex) {
		const swapTarget = Math.floor(Math.random() * (shuffled.length - 1)) + 1;
		[shuffled[0], shuffled[swapTarget]] = [shuffled[swapTarget], shuffled[0]];
	}

	shufflePool = shuffled;
}

/**
 * Handler utama untuk mengambil quote Uma Musume
 * - Random variatif teratur (Fair Shuffle Cycle)
 * - Anti-duplikasi beruntun
 * @returns {{ name: string, title: string, quote: string, index: number, total: number }}
 */
export function getUmaQuote() {
	if (!shufflePool || shufflePool.length === 0) {
		refillPool();
	}

	const nextIndex = shufflePool.pop();
	lastIndex = nextIndex;
	const selected = umaQuotes[nextIndex] || umaQuotes[0];

	return {
		name: selected.name,
		title: selected.title,
		quote: selected.quote,
		index: nextIndex + 1,
		total: umaQuotes.length
	};
}

